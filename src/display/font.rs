//! Bitmap fonts for the MK3 displays.
//!
//! Terminus glyphs (SIL OFL 1.1) baked in at build time so the driver has no
//! runtime font dependency. Only printable ASCII (0x20..0x7e) is included --
//! the screens are used for short parameter labels, not prose.

/// A monospaced bitmap font: one bit per pixel, rows packed MSB-first.
pub struct Font {
    /// Glyph width in pixels.
    pub w: usize,
    /// Glyph height in pixels.
    pub h: usize,
    /// Bytes per glyph row.
    pub stride: usize,
    /// Glyph bitmaps for ASCII 0x20..=0x7e, in order.
    pub glyphs: &'static [u8],
}

impl Font {
    /// Rows of the glyph for `ch`, falling back to space for anything unprintable.
    pub fn glyph(&self, ch: char) -> &'static [u8] {
        let c = ch as usize;
        let idx = if (0x20..=0x7e).contains(&c) { c - 0x20 } else { 0 };
        let per = self.stride * self.h;
        &self.glyphs[idx * per..(idx + 1) * per]
    }

    /// Whether the pixel at (`x`, `y`) inside the glyph for `ch` is set.
    pub fn pixel(&self, ch: char, x: usize, y: usize) -> bool {
        if x >= self.w || y >= self.h {
            return false;
        }
        let g = self.glyph(ch);
        g[y * self.stride + x / 8] & (0x80 >> (x % 8)) != 0
    }
}

